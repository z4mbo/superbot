/**
 * The bot mark's clips: short keyframed moves that turn, shift, squash and zoom the body and change
 * its face. Keys are `[seconds, ...values, x1, y1, x2, y2]`, the last four the cubic easing from
 * that key to the next. `rot` is pitch, yaw and roll in degrees from facing straight ahead, `pos`
 * moves the body in radii (y up), `squash` scales x and y about `anchor` (-1 is the bottom, 0 the
 * middle), `zoom` is the body's diameter as a share of the box, `lids` closes the eyes, `faces`
 * changes the face and `blinks` are moments the eyes blink. `rest` is where a move into the clip
 * aims. Written from local measurements of the reference's clips; edit by re-measuring.
 */

